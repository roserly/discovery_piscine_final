#!/usr/bin/env python

user_first_number = float(input("Give me first number: "))
user_second_number = float(input("Give me second number: "))
print (f"{user_first_number} + {user_second_number} = {user_first_number + user_second_number}")
print (f"{user_first_number} - {user_second_number} = {user_first_number - user_second_number}")
print (f"{user_first_number} / {user_second_number} = {user_first_number / user_second_number}")
print (f"{user_first_number} * {user_second_number} = {user_first_number * user_second_number:g}")

